//! `todoer skill`: prints the agent workflow, or writes it as a skill.

use crate::args::{Args, Flag, switch};
use crate::git;
use crate::logger;
use crate::project::write_file;
use std::path::{Path, PathBuf};

pub const SKILL: &str = include_str!("../templates/SKILL.md");
const TARGETS: [(&str, &str); 2] = [
    (".agents/skills/todoer/SKILL.md", "Codex, Cursor"),
    (".claude/skills/todoer/SKILL.md", "Claude Code, Cursor"),
];
/// Marks a skill file written by `todoer skill --init`. `todoer update`
/// rewrites only the files that still have it.
const MARKER: &str = "<!-- Generated by `todoer skill --init`";

/// `--refresh` is not in the help: `todoer update` runs the new binary with it.
pub const FLAGS: &[Flag] = &[switch("init", None), switch("refresh", None)];

pub fn workflow() -> &'static str {
    SKILL
        .strip_prefix("---\n")
        .and_then(|rest| rest.split_once("\n---\n"))
        .map(|(_, body)| body.trim_start())
        .unwrap_or(SKILL)
}

/// The skill with the marker line right after the front matter, where the
/// agents still read the front matter.
fn generated_skill() -> String {
    let marker = format!(
        "{MARKER}. `todoer update` rewrites this file; delete this line to keep your own changes. -->\n"
    );
    match SKILL
        .strip_prefix("---\n")
        .and_then(|rest| rest.find("\n---\n"))
    {
        Some(end) => {
            let split = "---\n".len() + end + "\n---\n".len();
            format!("{}{marker}{}", &SKILL[..split], &SKILL[split..])
        }
        None => format!("{marker}{SKILL}"),
    }
}

fn is_generated(text: &str) -> bool {
    text.lines().any(|line| line.starts_with(MARKER))
}

pub fn run(args: &Args) -> Result<(), String> {
    args.expect_positional(0, 0, "todoer skill [--init]")?;
    if args.has("refresh") {
        refresh();
        return Ok(());
    }
    if !args.has("init") {
        print!("{}", workflow());
        return Ok(());
    }
    let cwd = std::env::current_dir()
        .map_err(|error| format!("cannot read the current folder: {error}"))?;
    let (root, global) = match git::toplevel(&cwd) {
        Some(root) => (root, false),
        None => (home_dir()?, true),
    };
    if global {
        println!(
            "not in a git repository - writing the skill to {} for all projects",
            root.display()
        );
    }
    let content = generated_skill();
    for (path, read_by) in TARGETS {
        let file = root.join(path);
        let action = if file.exists() { "updated" } else { "wrote" };
        write_file(&file, &content)?;
        println!("{action} {path}  ({read_by})");
    }
    Ok(())
}

/// The skill files under `root` that still have the marker.
fn generated_files(root: &Path) -> Vec<PathBuf> {
    TARGETS
        .iter()
        .map(|(path, _)| root.join(path))
        .filter(|file| std::fs::read_to_string(file).is_ok_and(|text| is_generated(&text)))
        .collect()
}

/// Rewrites the skills that `todoer skill --init` wrote, when they still have
/// the marker: the ones in the root of the git repository of the current
/// folder, else (no repository, or no generated skill in it) the ones in the
/// home folder. Prints the files it changed. `todoer update` runs it with the
/// new binary (`todoer skill --refresh`), so the new skill text is written.
pub fn refresh() {
    let files = std::env::current_dir()
        .ok()
        .and_then(|cwd| git::toplevel(&cwd))
        .map(|root| generated_files(&root))
        .filter(|files| !files.is_empty())
        .or_else(|| home_dir().ok().map(|home| generated_files(&home)))
        .unwrap_or_default();

    let content = generated_skill();
    let mut updated = Vec::new();
    for file in files {
        if std::fs::read_to_string(&file).is_ok_and(|text| text == content) {
            continue;
        }
        match write_file(&file, &content) {
            Ok(()) => updated.push(file),
            Err(error) => logger::error(&format!("cannot update the skill: {error}")),
        }
    }
    if !updated.is_empty() {
        logger::info("updated skills:");
        for file in &updated {
            logger::info(&format!("  {}", file.display()));
        }
    }
}

fn home_dir() -> Result<PathBuf, String> {
    std::env::var_os("HOME")
        .filter(|home| !home.is_empty())
        .map(PathBuf::from)
        .ok_or_else(|| {
            "this folder is not in a git repository and HOME is not set - set HOME".to_string()
        })
}
